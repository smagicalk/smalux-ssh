# 完整编译全量 1456+ 词条的英文翻译字典，杜绝任何漏译与 msgstr 中文回退。

[Console]::OutputEncoding = [System.Text.Encoding]::UTF8

$root = if ($PSScriptRoot) { (Resolve-Path "$PSScriptRoot/..").Path } else { (Resolve-Path ".").Path }
$uiDir = "$root/crates/smagical-ui-view/ui"
$poDir = "$root/crates/smagical-ui-view/translations/en/LC_MESSAGES"
$dictJson = "$root/crates/smagical-ui-view/translations/en_dict.json"

Write-Host "1. 扫描所有 Slint 文件提取 @tr(...) 文本..."
$slintFiles = Get-ChildItem -Path $uiDir -Recurse -Filter "*.slint"
$allStrings = [System.Collections.Generic.HashSet[string]]::new()

foreach ($file in $slintFiles) {
    $txt = [System.IO.File]::ReadAllText($file.FullName, [System.Text.Encoding]::UTF8)
    $m = [regex]::Matches($txt, '@tr\("((?:[^"\\]|\\.)*)"\)')
    foreach ($item in $m) {
        $val = $item.Groups[1].Value.Replace('\"', '"')
        if ($val -match '[\u4e00-\u9fa5]') {
            [void]$allStrings.Add($val)
        }
    }
}
Write-Host "共提取出 $($allStrings.Count) 个包含中文的 @tr 字符串。"

# 从现有 en_dict.json 加载
$dict = [System.Collections.Generic.Dictionary[string, string]]::new()
if (Test-Path $dictJson) {
    $raw = Get-Content $dictJson -Raw -Encoding UTF8 | ConvertFrom-Json
    foreach ($prop in $raw.PSObject.Properties) {
        $v = $prop.Value
        if (-not [string]::IsNullOrWhiteSpace($v) -and $v -notmatch '[\u4e00-\u9fa5]') {
            $dict[$prop.Name] = $v
        }
    }
}
Write-Host "现有纯英文词条: $($dict.Count)"

