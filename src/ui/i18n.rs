pub(super) fn page_title(state: &AppState) -> &'static str {
    match state.ui.workspace.active_page {
        WorkspacePage::Hosts => t(state, "nav.hosts"),
        WorkspacePage::Terminal => t(state, "nav.terminal"),
        WorkspacePage::Sftp => t(state, "nav.sftp"),
        WorkspacePage::Tunnels => t(state, "nav.tunnels"),
        WorkspacePage::Snippets => t(state, "nav.snippets"),
        WorkspacePage::History => t(state, "nav.history"),
        WorkspacePage::Security => t(state, "nav.security"),
        WorkspacePage::Settings => t(state, "nav.settings"),
    }
}

pub(super) fn host_list_mode_label(state: &AppState) -> &'static str {
    match state.ui.workspace.host_list_mode {
        HostListMode::List => "List",
        HostListMode::Card => "Card",
    }
}

pub(super) fn theme_name(theme: BuiltInTheme) -> &'static str {
    match theme {
        BuiltInTheme::ProfessionalDark => "Professional Dark",
        BuiltInTheme::OceanDark => "Ocean Dark",
        BuiltInTheme::ForestDark => "Forest Dark",
    }
}

pub(super) fn background_label(source: &ImageSource) -> &str {
    match source {
        ImageSource::LocalPath(path) | ImageSource::Url(path) => path,
    }
}
